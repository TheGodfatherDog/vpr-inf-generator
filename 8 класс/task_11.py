# АРХЕТИП 2: КОЛИЧЕСТВО ВЕРШИН ЗВЕЗДЫ ИЛИ МНОГОУГОЛЬНИКА (35% — примеры 6–9, 31–37)
# =============================================================================

def generate_star_vertices():
    # Пул углов и точная классификация (звезда / многоугольник)
    # (угол, тип_фигуры)
    presets = [
        (108, "звезды"),
        (135, "звезды"),
        (140, "звезды"),
        (144, "звезды"),
        (160, "звезды"),
        (162, "звезды"),
        (200, "звезды"),
        (216, "звезды"),
        (336, "многоугольника"),
        (320, "многоугольника"),
        (400, "многоугольника")
    ]
    angle, shape_name = random.choice(presets)

    eff_angle = angle % 360
    if eff_angle == 0:
        eff_angle = 360

    vertices = 360 // math.gcd(eff_angle, 360)

    # Количество повторений достаточно для полного замыкания контура
    k = max(vertices, random.randint(15, 25))
    step = random.choice([3, 4, 5, 6])

    algo = f"повтори {k} [вперед({step}) вправо({angle})]"

    prompt = (
        f"{INSTRUCTION}\n\n"
        f"Черепахе был дан для исполнения следующий алгоритм, который строит фигуру:\n"
        f"{algo}\n\n"
        f"Выполните этот алгоритм в среде исполнителя «Черепаха» и определите количество вершин у {shape_name}."
    )

    return prompt, str(vertices)

# =============================================================================
# АРХЕТИП 3: ТОЧКИ НА ЛИНИЯХ КОНТУРА (15% — примеры 2–5)
# =============================================================================

def generate_points_on_lines():
    is_octagon = random.choice([True, False])

    if is_octagon:
        # Примеры 4, 5: Повтори 8 [Направо 45 Вперёд L]
        step = random.choice([4, 6, 8, 10])
        # Точная геометрическая формула количества целых точек
        ans = step + 2 * int(step / math.sqrt(2)) + 1

        algo = f"Повтори 8 [Направо 45 Вперёд {step}]"
        prompt = (
            f"{INSTRUCTION}\n\n"
            f"Черепаха выполнила следующую программу:\n"
            f"{algo}\n\n"
            "Определите, сколько различных точек с целочисленными координатами будет находиться "
            "на линиях, полученных при выполнении данной программы."
        )
        return prompt, str(ans)

    else:
        # Примеры 2, 3: Ступенчатая ортогональная траектория
        a = random.randint(5, 8)
        b = random.randint(8, 12)
        c = random.randint(4, 7)

        # Выверенная формула: 3*a + b + 3*c - 1
        ans = 3 * a + b + 3 * c - 1

        algo = (
            f"Повтори 3 [Вперёд {a} Направо 90]\n"
            f"Вперёд {b}\n"
            f"Повтори 3 [Налево 90 Вперёд {c}]"
        )

        prompt = (
            f"{INSTRUCTION}\n\n"
            f"Черепаха выполнила следующую программу:\n"
            f"{algo}\n\n"
            "Определите, сколько различных точек с целочисленными координатами будет находиться "
            "на линиях, полученных при выполнении данной программы."
        )
        return prompt, str(ans)

# =============================================================================
# ТОЧКА ВХОДА ГЕНЕРАТОРА
# =============================================================================

def generate():
    random.seed(os.urandom(16))

    archetype = random.choices(["inside", "star", "lines"], weights=[0.50, 0.35, 0.15], k=1)[0]

    if archetype == "inside":
        prompt, answer = generate_points_inside()
    elif archetype == "star":
        prompt, answer = generate_star_vertices()
    else:
        prompt, answer = generate_points_on_lines()

    return {
        "task": prompt,
        "variants": None,
        "variant_type": None,
        "answer": answer
    }

