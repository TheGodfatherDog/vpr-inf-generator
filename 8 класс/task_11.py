def generate_points_inside():
    # 50% прямоугольники/квадраты (аналитически), 50% правильные многоугольники
    is_rect = random.choice([True, False])

    if is_rect:
        is_square = random.choice([True, False])
        if is_square:
            a = random.randint(3, 8)
            algo = f"повтори 4 [вперед({a}) вправо(90)]"
            ans = (a - 1) * (a - 1)
        else:
            a = random.randint(4, 9)
            b = random.randint(2, a - 1)
            algo = f"повтори 2 [вперёд({a}) вправо(90) вперёд({b}) вправо(90)]"
            ans = (a - 1) * (b - 1)

        prompt = (
            f"{INSTRUCTION}\n\n"
            f"Черепахе был дан следующий алгоритм:\n"
            f"{algo}\n\n"
            "Постройте многоугольник в среде исполнителя «Черепаха» и определите количество точек "
            "с целыми координатами, находящихся строго внутри фигуры (точки на границе считать не нужно)."
        )
        return prompt, str(ans)

    else:
        algo, ans = random.choice(POLYGON_INNER_POINTS)
        prompt = (
            f"{INSTRUCTION}\n\n"
            f"Черепахе был дан следующий алгоритм:\n"
            f"{algo}\n\n"
            "Постройте многоугольник в среде исполнителя «Черепаха» и определите количество точек "
            "с целыми координатами, находящихся строго внутри фигуры (точки на границе считать не нужно)."
        )
        return prompt, str(ans)

